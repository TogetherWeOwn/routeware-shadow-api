#!/usr/bin/env node
/**
 * Writes out/curl-examples.sh and out/bodies/* — uses harvest requestBodyPreview
 * when present, otherwise copies route-map exampleFile.
 * Respects Content-Type (JSON vs form-urlencoded) from harvest or route-map.
 */
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { curlExampleForEntry, findHarvestRow } from "./lib/curlExamples.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const harvestPath = join(__dirname, "out", "harvest.ndjson");
const mapPath = join(__dirname, "route-map.json");
const bodiesDir = join(__dirname, "out", "bodies");
const outSh = join(__dirname, "out", "curl-examples.sh");

const map = JSON.parse(await readFile(mapPath, "utf8"));
let harvestLines = [];
try {
  harvestLines = (await readFile(harvestPath, "utf8"))
    .split(/\n/)
    .filter((l) => l.trim());
} catch {
  console.warn("No harvest.ndjson; using example files only.");
}

await rm(bodiesDir, { recursive: true, force: true }).catch(() => {});
await mkdir(bodiesDir, { recursive: true });

const sh = [
  "#!/usr/bin/env bash",
  "# Generated by export-curl-examples.mjs — re-run after recording.",
  "set -euo pipefail",
  'BASE="${BASE:-http://localhost:8787}"',
  'DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
  ""
];

for (const entry of map) {
  const row = findHarvestRow(harvestLines, entry.method, entry.upstreamPath);
  let bodyText = null;
  if (row?.requestBodyPreview) {
    bodyText = String(row.requestBodyPreview).trim();
  } else if (entry.exampleFile) {
    bodyText = (await readFile(join(__dirname, entry.exampleFile), "utf8")).trim();
  }

  const rendered = curlExampleForEntry(entry, row, bodyText);
  if (rendered.bodyFile) {
    await writeFile(join(bodiesDir, rendered.bodyFile.fileName), rendered.bodyFile.text, "utf8");
  }
  sh.push(...rendered.lines);
}

await writeFile(outSh, sh.join("\n"), "utf8");
console.log("Wrote", outSh);
console.log("Body files under", bodiesDir);
console.log("Run: BASE=http://localhost:8787 bash", outSh);
