/** Embedded in the generated shell file; keep dependencies explicit and local. */
export function runCurlPlan(plan, args, env, spawn) {
  let selector;
  const flags = new Set();
  const fail = (code) => { throw new Error(code); };
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === "--operation") {
      if (selector !== undefined || !args[i + 1] || args[i + 1].startsWith("--")) {
        fail("INVALID_OPERATION: supply exactly one method/path identity from --list");
      }
      selector = args[++i];
    } else if (["--help", "--list", "--dry-run", "--json"].includes(arg) && !flags.has(arg)) {
      flags.add(arg);
    } else {
      fail("INVALID_ARGUMENT: see --help for supported flags");
    }
  }
  const matches = selector === undefined ? plan.operations : plan.operations.filter((op) => op.id === selector);
  if (selector !== undefined && matches.length !== 1) {
    fail("UNKNOWN_OPERATION: select an exact method/path identity from --list");
  }
  const selectedPlan = { schemaVersion: plan.schemaVersion, operations: matches };
  if (flags.has("--json")) {
    console.log(JSON.stringify(selectedPlan, null, 2));
    return 0;
  }
  if (flags.has("--help")) {
    console.log("Usage: bash curl-examples.sh [--operation 'METHOD /WebRW/Path'] [--list | --help | --dry-run | --json]\nOnly an explicitly selected GET can execute, against loopback BASE (default http://localhost:8787).\nNo selection lists operations. --dry-run and --json are inert plans. Non-GET examples are documentation only.\nBASE permits http(s)://localhost, 127.0.0.1 or [::1], optionally with a port; no credentials, path, query or fragment.");
  }
  if (selector === undefined || flags.has("--help") || flags.has("--list") || flags.has("--dry-run")) {
    for (const op of matches) console.log(`${op.id} — ${op.executable ? "local GET only" : "non-executable documentation"}; body=${op.body.source}${op.body.code ? `; ${op.body.code}: ${op.body.next_action}` : ""}`);
    return 0;
  }
  const op = matches[0];
  if (op.method !== "GET" || !op.executable) fail("NON_EXECUTABLE: only selected GET examples can execute");
  let base;
  try {
    const raw = env.BASE ?? "http://localhost:8787";
    if (!/^https?:\/\/(?:localhost|127\.0\.0\.1|\[::1\])(?::[0-9]+)?\/?$/i.test(raw)) fail("INVALID_BASE");
    base = new URL(raw);
    if (!["http:", "https:"].includes(base.protocol) ||
        !["localhost", "127.0.0.1", "[::1]"].includes(base.hostname) ||
        base.username || base.password || base.hash || base.search || base.pathname !== "/") fail("INVALID_BASE");
  } catch {
    fail("INVALID_BASE: use a loopback HTTP(S) origin without credentials, path, query or fragment");
  }
  // Do not let map paths, URL normalization, curl globbing or redirect settings
  // turn a local selection into a second request or a different authority.
  if (!op.urlPath.startsWith("/") || op.urlPath.startsWith("//") || /[\s\\#\x00-\x1f\x7f]/.test(op.urlPath)) fail("INVALID_LOCAL_PATH");
  const url = base.origin + op.urlPath;
  if (new URL(url).origin !== base.origin) fail("INVALID_LOCAL_PATH");
  const localResolution = base.hostname === "localhost"
    ? ["--resolve", `localhost:${base.port || (base.protocol === "https:" ? "443" : "80")}:127.0.0.1`]
    : [];
  const result = spawn("curl", [
    "-q", ...localResolution, "--noproxy", "*", "--proxy", "", "--globoff", "--proto", "=http,https",
    "--connect-timeout", "5", "--max-time", "30", "--fail", "-sS",
    "-H", "Accept: */*", "-H", "X-Requested-With: XMLHttpRequest", "--url", url,
  ], { stdio: "inherit", timeout: 35_000 });
  if (result.error || result.signal) fail("CURL_FAILED: curl unavailable, interrupted or timed out");
  return result.status ?? 1;
}

export function renderCurlScript(plan, examples) {
  const documentation = examples.flatMap(({ lines }) => lines.map((line) =>
    line && !line.startsWith("#") ? `# ${line}` : line));
  return [
    "#!/usr/bin/env bash",
    "# Generated by export-curl-examples.mjs. No selection means no network.",
    "# Requires Node.js and curl; non-GET material below is documentation only.",
    "set -euo pipefail",
    "exec node --input-type=module - \"$@\" <<'CURL_EXAMPLES_NODE'",
    'import { spawnSync } from "node:child_process";',
    runCurlPlan.toString(),
    `const plan = JSON.parse(${JSON.stringify(JSON.stringify(plan))});`,
    "try { process.exitCode = runCurlPlan(plan, process.argv.slice(2), process.env, spawnSync); }",
    "catch (error) { console.error(error.message); process.exitCode = 1; }",
    "CURL_EXAMPLES_NODE",
    "",
    ...documentation,
  ].join("\n");
}
